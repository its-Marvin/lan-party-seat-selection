"""Storage helpers: SQLite by default, PostgreSQL when ``DATABASE_URL`` is set.

Application code is written once, in SQLite style (``?`` placeholders, rows
indexable by name and position). ``PgConnection`` adapts that to psycopg, so
both backends share the same queries and the same transaction rules:

* ``write_transaction()`` serialises all writers: ``BEGIN IMMEDIATE`` in SQLite,
  a transaction-level advisory lock in PostgreSQL. Like SQLite, PostgreSQL also
  takes that lock for implicit write transactions (a write outside the block,
  followed by ``commit()``), so no write can slip in between.
* ``read_snapshot()`` sees one consistent state: a deferred transaction in
  SQLite, ``REPEATABLE READ`` in PostgreSQL.

SQL must stay portable: no SQLite-only functions such as ``datetime('now')``
(pass ``utc_now()`` as a parameter), ``INSERT OR IGNORE`` (use ``ON CONFLICT
DO NOTHING``) or ``lastrowid`` (use ``db.insert()``).
"""

from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from functools import lru_cache
import json
import re
import sqlite3

from flask import current_app, g

try:
    import psycopg
except ImportError:  # only needed for PostgreSQL
    psycopg = None

IntegrityError = (sqlite3.IntegrityError, *((psycopg.IntegrityError,) if psycopg else ()))


def is_unavailable(err: BaseException) -> bool:
    """The database is busy (lock timeout) or unreachable: worth a retry (503),
    unlike a bug in a query (500)."""
    if isinstance(err, sqlite3.OperationalError):
        return "locked" in str(err) or "busy" in str(err)
    # psycopg's OperationalError: connection lost or refused, lock_timeout (LockNotAvailable)
    return psycopg is not None and isinstance(err, psycopg.OperationalError)

